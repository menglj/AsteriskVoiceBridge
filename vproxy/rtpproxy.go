type IOProxy struct {
	srcAddr *net.IPAddr
	dstAddr *net.IPAddr

	session        *rtp.Session
	transport      *rtp.TransportUDP
	stopLocalRecv  chan bool
	stopRemoteSend chan bool

	pauseAudio  chan bool
	resumeAudio chan bool

	disengageOutbound chan bool
	disengageInbound  chan bool
	engageOutbound    chan bool
	engageInbound     chan bool

	syncout chan bool

	outboundssrc  uint32
	outboundstamp uint32
}

func (vudp *IOProxy) initialize() {
	vudp.stopLocalRecv = make(chan bool)
	vudp.stopRemoteSend = make(chan bool)
	vudp.pauseAudio = make(chan bool)
	vudp.resumeAudio = make(chan bool)
	vudp.disengageOutbound = make(chan bool)
	vudp.disengageInbound = make(chan bool)
	vudp.engageOutbound = make(chan bool)
	vudp.engageInbound = make(chan bool)
	vudp.syncout = make(chan bool)
}

func CreateRTPPProxy(dstMediaAddress string, dstMediaPort int,
    srcMediaAddress string, srcMediaPort int) (*IOProxy, bool) {

    // Local should bind to our ExternalMedia host/port (dstMediaAddress:dstMediaPort)
    // Remote should be Asterisk's RTP address/port (srcMediaAddress:srcMediaPort)
    local, err := net.ResolveIPAddr("ip", dstMediaAddress)
	if err != nil {
		log.Error("RTP:CreateRTPPProxy", "ResolveIPAddr Error", err)
		return &IOProxy{}, false
	}
    remote, err := net.ResolveIPAddr("ip", srcMediaAddress)
	if err != nil {
		log.Error("RTP:CreateRTPPProxy", "ResolveIPAddr Error", err)
		return &IOProxy{}, false
	}

    tpLocal, err := rtp.NewTransportUDP(local, dstMediaPort, "")
	if err != nil {
		log.Error("RTP:CreateRTPPProxy", "NewTransportUDP Error", err)
		return &IOProxy{}, false
	}

	rsLocal := rtp.NewSession(tpLocal, tpLocal)
    remoteadd := &rtp.Address{IPAddr: remote.IP, DataPort: srcMediaPort, CtrlPort: srcMediaPort + 1, Zone: ""}
	rsLocal.AddRemote(remoteadd)

	ssrcid := generateRandomSSRCID()
    strLocalIdx, err := rsLocal.NewSsrcStreamOut(&rtp.Address{IPAddr: local.IP, DataPort: dstMediaPort, CtrlPort: dstMediaPort + 1, Zone: ""}, ssrcid, 3200)
	if err.Error() != "" {
		log.Error("RTP:CreateRTPPProxy", "NewSsrcStreamOutErr", err.Error())
	}

	ptype := byte(GetRTP_PAYLOAD_TYPE())
	log.Info("RTP:CreateRTPPProxy", "PayloadType", ptype)
	rsLocal.SsrcStreamOutForIndex(strLocalIdx).SetPayloadType(ptype)

	proxy := &IOProxy{srcAddr: local, dstAddr: remote, session: rsLocal, transport: tpLocal, outboundssrc: ssrcid}
	proxy.initialize()

	log.Info("RTP:CreateRTPPProxy", "Event", "Created")
	return proxy, true
}

func (vudp *IOProxy) stopSend() {
	log.Debug("RTP:StopSend", "Event", "Sending")
	vudp.stopLocalRecv <- true
	log.Debug("RTP:StopSend", "Event", "Sent")
}

func (vudp *IOProxy) stopRecv() {
	log.Debug("RTP:StopRecv", "Event", "Sending")
	vudp.stopRemoteSend <- true
	log.Debug("RTP:StopRecv", "Event", "Sent")
}

func (vudp *IOProxy) Stop() bool {
	log.Info("RTP:Stop", "Event", "Stop")
	if vudp == nil || vudp.stopLocalRecv == nil || vudp.stopRemoteSend == nil {
		log.Error("RTP:Stop", "Error", "StopChannels are NULL")
		return false
	}
	go vudp.stopSend()
	go vudp.stopRecv()
	vudp.session.CloseSession()
	vudp.transport.CloseRecv()
	vudp.transport.CloseWrite()

	return true
}

func (vudp *IOProxy) Disengage() {
	log.Info("RTP:Disengage", "Event", "Disengaging")
	vudp.disengageInbound <- true
	vudp.disengageOutbound <- true
	log.Info("RTP:Disengage", "Event", "Disengaged")
}

func (vudp *IOProxy) Engage() {
	log.Info("RTP:Engage", "Event", "Engaging")
	vudp.engageInbound <- true
	vudp.engageOutbound <- true
	log.Info("RTP:Engage", "Event", "Engaged")
}

// copy data from udpConn to io.Writer, ie send to stt engine
func (p *IOProxy) StreamTo(w io.Writer) error {
	log.Info("RTP:StreamTo", "Event", "Start")
	dataReceiver := p.session.CreateDataReceiveChan()
	if dataReceiver == nil {
		log.Error("RTP:StreamTo", "Error", "DataReceiver is NULL")
		return fmt.Errorf("DataReceiver is NULL")
	}

	controlReceiver := p.session.CreateCtrlEventChan()
	if controlReceiver == nil {
		log.Error("RTP:StreamTo", "Error", "ControlReceiver is NULL")
		return fmt.Errorf("ControlReceiver is NULL")
	}

	err := p.session.ListenOnTransports()
	if err != nil {
		log.Error("RTP:StreamTo", "Error", "ListenOnTransports", "Error", err.Error())
	}
	log.Info("RTP:StreamTo", "Event", "Listening")

	engaged := true
	for {
		select {
		case ev := <-controlReceiver:
			log.Info("RTP:StreamTo", "Event", "ControlEventReceived", "Event", ev)
		case rp := <-dataReceiver:
			log.Debug("RTP:StreamTo", "Event", "PacketDataReceived")
			if w != nil && engaged {
				_, err := w.Write(rp.Payload())
				if err != nil {
					fmt.Println("StreamTo", "Write Error", err)
					return err
				}
			}
			rp.FreePacket()
			p.syncout <- true
		case <-p.disengageOutbound:
			log.Info("RTP:StreamTo", "Event", "Disengage")
			engaged = false
			continue
		case <-p.engageOutbound:
			log.Info("RTP:StreamTo", "Event", "Engage")
			engaged = true
			continue
		case <-p.stopLocalRecv:
			log.Info("RTP:StreamTo", "Event", "Stop")
			return nil
		}
	}
}

