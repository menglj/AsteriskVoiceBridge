func GetDeadWord() []byte {
	deadWord := [4]byte{0xde, 0xad, 0xbe, 0xef}
	return deadWord[:]
}

func ContainsDeadPacket(buf []byte) (bool, int) {
	deadword := GetDeadWord()
	if bytes.Contains(buf, deadword) {
		return true, bytes.Index(buf, deadword)
	} else {
		return false, 0
	}
}

// TODO replace io with a fifo frame queue
// copy data from io.Reader to udpConn, ie read from tts engine
func (p *IOProxy) StreamFrom(r io.Reader, streamdone chan bool, wakefile chan bool, filerevived chan bool, deadf chan bool) error {
	log.Info("RTP:StreamFrom", "Event", "Start")

	cnPacket := GetSilentPacket()

	pauseAudio := false
	engaged := true
	deadfile := true
	wassilent := false

	iterations := 0
	packetsSinceLastDead := 0

	for {
		select {
		case <-p.stopRemoteSend:
			log.Info("RTP:StreamFrom", "Event", "Stop")
			streamdone <- true
			return nil
		case <-p.pauseAudio:
			log.Info("RTP:StreamFrom", "Event", "PauseAudio")
			pauseAudio = true
			continue
		case <-p.resumeAudio:
			log.Info("RTP:StreamFrom", "Event", "ResumeAudio")
			pauseAudio = false
			continue
		case <-p.disengageInbound:
			log.Info("RTP:StreamFrom", "Event", "Disengage")
			engaged = false
			continue
		case <-p.engageInbound:
			log.Info("RTP:StreamFrom", "Event", "Engage")
			engaged = true
			continue
		case <-wakefile:
			log.Info("RTP:StreamFrom", "Event", "WakeFileReceived", "DeadFile", deadfile)
			if deadfile {
				log.Info("RTP:StreamFrom", "Event", "WakeFile")
				deadfile = false
				filerevived <- true
			} else {
				log.Info("RTP:StreamFrom", "Event", "WakeFileIgnored", "Reason", "DeadFile already false")
			}
			continue
		case <-p.syncout:
			rtpPacket := p.session.NewDataPacket(p.outboundstamp)

			if !pauseAudio && !deadfile && engaged {
				if wassilent {
					log.Info("RTP:StreamFrom", "Event", "SpeechStart")
					wassilent = false
				}

				iterations++
				if iterations%50 == 0 {
					log.Info("RTP:StreamFrom", "Event", "StreamingSpeech")
					iterations = 0
				}
				packetsSinceLastDead++

				buf := make([]byte, GetRTP_PAYLOAD_SIZE())
				n, err := r.Read(buf)

				if err == io.EOF {
					log.Info("RTP:StreamFrom", "Event", "EOF")
					deadfile = true
				} else if err != nil {
					for n < GetRTP_PAYLOAD_SIZE() {
						log.Debug("RTP:StreamFrom", "Event", "PartialRead", "Bytes", n)
						m, merr := r.Read(buf[n:])
						log.Debug("RTP:StreamFrom", "Event", "AdditionalBytes", "Bytes", m)
						n = n + m
						err = merr
						if err != nil {
							log.Info("RTP:StreamFrom", "ReadError", err)
							break
						}
					}
					log.Debug("RTP:StreamFrom", "Event", "ReadEnd", "Bytes", n)
				}

				if err != nil {
					if err == io.EOF {
						// our pipe was closed, this is ok, it means we are being woken to
						// indicate we are done or restarting.
						// either way the above signals will handle what to do next
						log.Info("RTP:StreamFrom", "Event", "EOF")
					} else {
						// On a cancel/restart we may get an error here, this is ok
						log.Info("RTP:StreamFrom", "ReadError", err)
					}
				} else {
					dead, dn := ContainsDeadPacket(buf)
					if dead {
						reallydead := true
						if dn == 0 {
							if bytes.Equal(buf, GetDeadPacket()) {
								log.Info("RTP:StreamFrom", "Event", "FullDeadPacket")
								reallydead = true
								n = dn
							} else {
								log.Info("RTP:StreamFrom", "Event", "FalseDeadPacket")
								dn = bytes.LastIndex(buf, GetDeadPacket()) + len(GetDeadPacket()) - 1
								//add comfort noise to the begining of the packet
								copy(buf[:dn], cnPacket[:dn])
								reallydead = false
							}
						} else {
							n = dn
						}

						if reallydead {
							log.Info("RTP:StreamFrom", "Event", "DeadFile")
							deadfile = true
							deadf <- true
							log.Info("RTP:StreamFrom", "SpeechPacketsSent", packetsSinceLastDead)
							packetsSinceLastDead = 0
						}
					}
				}

				if n < GetRTP_PAYLOAD_SIZE() {
					// copy everything after n from cnPacket to buf to avoid 'pops' in audio
					copy(buf[n:], cnPacket[:])
					log.Error("RTP:StreamFrom", "Event", "AppendedSilence", "Bytes", GetRTP_PAYLOAD_SIZE()-n)
				}

				rtpPacket.SetPayload(buf[:])
			} else {
				if !wassilent {
					log.Info("RTP:StreamFrom", "Event", "SilenceStart")
					wassilent = true
				}
				iterations++
				if iterations%50 == 0 {
					log.Info("RTP:StreamFrom", "Event", "StreamingSilence")
					iterations = 0
					if !deadfile {
						log.Info("RTP:StreamFrom", "Reason", "PausedOrNotEngaged")
					}
				}
				// send silence
				rtpPacket.SetPayload(cnPacket[:])
			}

			p.session.WriteData(rtpPacket)
			rtpPacket.FreePacket()
			p.outboundstamp += GetRTP_PAYLOAD_SIZE_U()
		}
	}
}

func (p *IOProxy) PauseAudio() {
	log.Info("RTP:Pause")
	p.pauseAudio <- true
}

func (p *IOProxy) ResumeAudio() {
	log.Info("RTP:Resume")
	p.resumeAudio <- true
}

func (p *IOProxy) StopAudio() {
	log.Info("RTP:StopAudio")
	p.stopRemoteSend <- true
}

// echo data back to the udp connection
func (p *IOProxy) Echo() error {
	log.Info("RTP:Echo", "Event", "Start")
	dataReceiver := p.session.CreateDataReceiveChan()
	p.session.ListenOnTransports()
	for {
		select {
		case rp := <-dataReceiver:
			np := rp.Clone()
			np.SetSsrc(p.outboundssrc)
			_, err := p.session.WriteData(np)
			if err != nil {
				log.Error("RTP:StreamTo", "Write Error", err)
				return err
			}
			rp.FreePacket()
		case <-p.stopLocalRecv:
			log.Info("RTP:StreamTo", "Event", "Stop")
			return nil
		}
	}
}
